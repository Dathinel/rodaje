[CmdletBinding()]
param()

$ErrorActionPreference = 'Stop'
$scriptDir = $PSScriptRoot

$entornoDir = $env:RODAJE_ENTORNO
if (-not $entornoDir -or -not (Test-Path $entornoDir)) {
    $entornoDir = Join-Path $scriptDir '..\..\..\.entorno'
}

$dxcCandidates = @(
    (Get-ChildItem -Path "$entornoDir\nuget\microsoft.direct3d.dxc" -Filter "dxc.exe" -Recurse -ErrorAction SilentlyContinue | Where-Object { $_.FullName -like "*x64*" } | Select-Object -First 1).FullName
)

$dxcPath = $dxcCandidates | Where-Object { $_ -and (Test-Path $_) } | Select-Object -First 1
if (-not $dxcPath) {
    throw "No se encontró dxc.exe en $entornoDir\nuget\microsoft.direct3d.dxc"
}

$hlslPath = Join-Path $scriptDir "convert.hlsl"
$spvPath = Join-Path $scriptDir "convert.spv"
$shadersCsPath = Join-Path $scriptDir "Shaders.cs"

if (-not (Test-Path $hlslPath)) {
    throw "No se encontró el archivo sombreador HLSL: $hlslPath"
}

Write-Host "Compilando $hlslPath con DXC ($dxcPath)..."
& $dxcPath -T cs_6_0 -E main -spirv "$hlslPath" -Fo "$spvPath"
if ($LASTEXITCODE -ne 0) {
    throw "Error compilando convert.hlsl con DXC (código de salida $LASTEXITCODE)"
}

try {
    $spvBytes = [System.IO.File]::ReadAllBytes($spvPath)
    $sb = [System.Text.StringBuilder]::new()
    [void]$sb.AppendLine("// <auto-generated/>")
    [void]$sb.AppendLine("namespace Rodaje.VulkanVideo;")
    [void]$sb.AppendLine("internal static class Shaders")
    [void]$sb.AppendLine("{")
    [void]$sb.AppendLine("    public static ReadOnlySpan<byte> ConvertSpv => new byte[]")
    [void]$sb.AppendLine("    {")

    for ($i = 0; $i -lt $spvBytes.Length; $i += 16) {
        $line = "        "
        for ($j = 0; $j -lt 16 -and ($i + $j) -lt $spvBytes.Length; $j++) {
            $line += "0x{0:X2}, " -f $spvBytes[$i + $j]
        }
        [void]$sb.AppendLine($line)
    }

    [void]$sb.AppendLine("    };")
    [void]$sb.AppendLine("}")

    $utf8NoBom = [System.Text.UTF8Encoding]::new($false)
    [System.IO.File]::WriteAllText($shadersCsPath, $sb.ToString(), $utf8NoBom)
    Write-Host "Shaders.cs generado exitosamente ($($spvBytes.Length) bytes SPIR-V)."
}
finally {
    if (Test-Path $spvPath) {
        Remove-Item $spvPath -Force
    }
}
